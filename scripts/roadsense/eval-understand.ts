// Typed what-ifs (2026-10-27 redesign): reads every phrase in data/roadsense/understand-phrases.json
// with understandWhatIf and scores the readings (scoreUnderstanding in lib/roadsense/eval.ts).
// Run from the repo root:
//
//   npx tsx scripts/roadsense/eval-understand.ts --mode live --record   calls Muse Spark and saves its replies
//   npx tsx scripts/roadsense/eval-understand.ts                        replays them: the same numbers, at $0
//
// Live runs use Standard mode at low reasoning effort, as learners' questions do. The script
// writes docs/roadsense/eval-understand.md and exits 1 unless no phrase is read as a wrong edit
// and at least 90% are read as expected (the redesign spec's gate, section 6.3). A changed
// prompt changes every call, so it needs a new recording. tsx loads this file as CommonJS: all in main().
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { scoreUnderstanding } from "../../lib/roadsense/eval";
import { createMetaClient, type MetaClient } from "../../lib/roadsense/meta-client";
import { createRecordingClient, createReplayClient } from "../../lib/roadsense/replay";
import type { WhatIfMatch } from "../../lib/roadsense/types";
import { parseWhatIfMatch, understandWhatIf } from "../../lib/roadsense/understand";
import { inPool, readModelKey } from "./env";

const PHRASES = resolve("data/roadsense/understand-phrases.json");
const RECORDING = resolve("data/roadsense/recordings/understand.json");
const REPORT = resolve("docs/roadsense/eval-understand.md");
const MIN_MATCHED = 0.9;
const CONCURRENCY = 4;

interface Case {
  text: string;
  expected: WhatIfMatch;
  got: WhatIfMatch;
}

function flag(name: string): string | undefined {
  const i = process.argv.indexOf(name);
  return i === -1 ? undefined : process.argv[i + 1];
}

const label = (match: WhatIfMatch): string => ("to" in match && match.to ? `${match.kind} (${match.to})` : match.kind);
const cell = (text: string): string => text.replace(/\|/g, "\\|").replace(/</g, "&lt;");

function report(cases: readonly Case[], meta: { mode: string; date: string; model: string }): string {
  const score = scoreUnderstanding(cases);
  const pct = Math.round((100 * score.matched) / score.total);
  const named = (c: Case): string | undefined => ("to" in c.expected ? c.expected.to : undefined);
  const off = cases.filter((c) => !(c.got.kind === c.expected.kind && (named(c) === undefined || ("to" in c.got && c.got.to === named(c)))));
  return [
    "# Understanding typed what-ifs",
    "",
    `Generated by \`scripts/roadsense/eval-understand.ts\` (${meta.mode}, ${meta.date}): ${score.total} phrases in Spanish, English, French and Arabic, read by ${meta.model} in Standard mode at low reasoning effort. Each phrase is read once, and the reading is compared with the edit the phrase asks for, or with "none" when RoadSense can't test it.`,
    "",
    "| Measure | Result | Target |",
    "|---|---|---|",
    `| Read as the expected edit | ${score.matched}/${score.total} (${pct}%) | ≥ 90% |`,
    `| Read as a wrong edit | ${score.wrong} | 0 |`,
    `| Read as "none" when an edit was meant | ${score.missed} | |`,
    "",
    "## Phrases not read as expected",
    "",
    ...(off.length === 0
      ? ["None."]
      : ["| Phrase | Expected | Read as |", "|---|---|---|", ...off.map((c) => `| ${cell(c.text)} | ${label(c.expected)} | ${label(c.got)} |`)]),
    "",
    "The phrases were written to test the prompt, which was tuned on them, so these numbers are in-sample. A wrong reading would show the learner the wrong change, so it must never happen; a phrase read as \"none\" only gets the honest reply that RoadSense can't test it yet.",
    "",
  ].join("\n");
}

async function main(): Promise<void> {
  const mode = flag("--mode") ?? "replay";
  if (mode !== "live" && mode !== "replay") throw new Error("--mode must be live or replay");
  const record = mode === "live" && process.argv.includes("--record");
  const phrases = (JSON.parse(readFileSync(PHRASES, "utf8")) as { text: string; expected: unknown }[]).map((phrase) => ({
    text: phrase.text,
    expected: parseWhatIfMatch(phrase.expected),
  }));
  const sink: Record<string, unknown> = {};
  let client: MetaClient;
  if (mode === "live") {
    const live = createMetaClient({ apiKey: readModelKey(), reasoningEffort: "low", timeoutMs: 60_000 });
    client = record ? createRecordingClient(live, sink) : live;
  } else {
    if (!existsSync(RECORDING)) throw new Error("no recording: run with --mode live --record first");
    client = createReplayClient(JSON.parse(readFileSync(RECORDING, "utf8")) as Record<string, unknown>);
  }

  const readings = new Map<number, { got: WhatIfMatch; costUsd: number }>();
  await inPool(
    phrases.map((phrase, i) => ({ phrase, i })),
    CONCURRENCY,
    async ({ phrase, i }) => {
      const { match, costUsd } = await understandWhatIf(client, phrase.text);
      readings.set(i, { got: match, costUsd });
    },
  );
  const cases: Case[] = phrases.map((phrase, i) => {
    const reading = readings.get(i);
    if (!reading) throw new Error(`no reading for "${phrase.text}"`);
    return { ...phrase, got: reading.got };
  });
  if (record) writeFileSync(RECORDING, `${JSON.stringify(sink, null, 2)}\n`);

  const date = new Date().toISOString().slice(0, 10);
  writeFileSync(REPORT, report(cases, { mode, date, model: client.sparkModel }));
  const score = scoreUnderstanding(cases);
  const costUsd = [...readings.values()].reduce((sum, reading) => sum + reading.costUsd, 0);
  process.stdout.write(`${score.matched}/${score.total} read as expected, ${score.wrong} wrong, ${score.missed} read as none; $${costUsd.toFixed(4)}\n`);
  for (const c of cases) if (label(c.got) !== label(c.expected)) process.stdout.write(`  "${c.text}": expected ${label(c.expected)}, read ${label(c.got)}\n`);
  if (score.wrong > 0 || score.matched / score.total < MIN_MATCHED) process.exitCode = 1;
}

main().catch((err: unknown) => {
  process.stderr.write(`${err instanceof Error ? `${err.name}: ${err.message}` : String(err)}\n`);
  process.exitCode = 1;
});
